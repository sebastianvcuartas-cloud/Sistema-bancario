    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
    try {
    String num = txtNumero.getText();
    String titular = txtTitular.getText();
    int d = Integer.parseInt(txtDia.getText());
    int m = Integer.parseInt(txtMes.getText());
    int a = Integer.parseInt(txtAño.getText());
    double saldo = Double.parseDouble(txtSaldo.getText());

    if (cmbTipoCuenta.getSelectedItem().toString().equals("Ahorros")) {
        controlador.CrearCuentaAhorros(num, titular, d, m, a, saldo);
    } else {
        double sobregiro = Double.parseDouble(txtSobregiro.getText());
        controlador.crearCuentaCorriente(num, titular, d, m, a, saldo, sobregiro);
    }

    txtResultado.setText("¡Cuenta creada exitosamente!\n\n" + controlador.consultarDatos(false));
} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(this, "Verifique que los campos numéricos sean válidos.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
}    // TODO add your handling code here:
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
    if (!controlador.HayCuenta()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Primero cree una cuenta.", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }
    try {
        double monto = Double.parseDouble(txtMontoOperacion.getText());
        if (controlador.consignar(monto)) {
            txtResultado.setText("¡Consignación exitosa!\n\n" + controlador.consultarDatos(false));
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "El monto a consignar debe ser mayor a 0.");
        }
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Ingrese un monto válido.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
    }    // TODO add your handling code here:
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
    if (!controlador.HayCuenta()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Primero cree una cuenta.", "Aviso", javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }
    try {
        double monto = Double.parseDouble(txtMontoOperacion.getText());
        boolean exito = controlador.retirar(monto);
        if (exito) {
            txtResultado.setText("¡Retiro realizado exitosamente!\n\n" + controlador.consultarDatos(false));
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Transacción rechazada: Saldo o cupo de sobregiro insuficiente.", "Error de Transacción", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Ingrese un monto válido.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
    }    // TODO add your handling code here:
    }//GEN-LAST:event_jButton3ActionPerformed

